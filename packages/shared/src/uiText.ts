const escapeRegex = (value: string): string => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const templateMessages = Object.entries(CHINESE_UI_MESSAGES)
  .flatMap(([source, translation]) => {
    const matches = [...source.matchAll(/\{value(\d+)\}/g)];
    if (matches.length === 0) return [];
    let offset = 0;
    let pattern = "^";
    for (const match of matches) {
      pattern += escapeRegex(source.slice(offset, match.index)) + "([\\s\\S]*?)";
      offset = match.index + match[0].length;
    }
    pattern += escapeRegex(source.slice(offset)) + "$";
    const fragments = source.split(/\{value\d+\}/).filter((fragment) => fragment.trim().length > 1);
    return [
      {
        expression: new RegExp(pattern),
        indices: matches.map((match) => match[1]!),
        translation,
        fragments,
        specificity: fragments.join("").length,
      },
    ];
  })
  .sort((left, right) => right.specificity - left.specificity);

const translatedCache = new Map<string, string>();

/** Translate built-in UI messages while retaining interpolated names, paths, and code verbatim. */
export function translateBuiltInUiSource(locale: ResolvedAppLocale, source: string): string {
  if (locale !== "zh-CN") return source;
  const direct = CHINESE_UI_MESSAGES[source];
  if (direct !== undefined) return direct;
  if (source.length > 4096) return source;
  const cached = translatedCache.get(source);
  if (cached !== undefined) return cached;
  for (const template of templateMessages) {
    if (!template.fragments.every((fragment) => source.includes(fragment))) continue;
    const match = template.expression.exec(source);
    if (!match) continue;
    const values = new Map(
      template.indices.map((index, position) => [index, match[position + 1] ?? ""]),
    );
    const translated = template.translation.replace(
      /\{value(\d+)\}/g,
      (_, index: string) => values.get(index) ?? "",
    );
    // Progress and timestamps create new strings continually; bound their cache.
    if (translatedCache.size >= 512) translatedCache.clear();
    translatedCache.set(source, translated);
    return translated;
  }
  if (translatedCache.size >= 512) translatedCache.clear();
  translatedCache.set(source, source);
  return source;
}
